import { readFileSync } from 'node:fs'
import { expect, it, vi } from 'vitest'
import { createClient, resourceType } from '../src/http/client'
import { createServiceOperationsClient, serviceQuery } from '../src/modules/operations'
it('decodes the service catalog without manufacturing legacy display fields', async () => {
  const body=JSON.parse(readFileSync(new URL('../fixtures/operation-services.json',import.meta.url),'utf8'))
  const transport=vi.fn().mockResolvedValue({status:200,headers:{'content-type':'application/vnd.api+json'},body})
  const api=createServiceOperationsClient(createClient(transport))
  const result=await api.catalog('school-one',{page:2,size:24,search:'便民 & 校园'})
  expect(result.token).toBe('4:1')
  expect(transport.mock.calls[0][0].path).toContain('/schools/school-one/operation-services?')
  expect(serviceQuery({page:2,search:'a & b'})).toBe('?page%5Bnumber%5D=2&search=a%20%26%20b')
})
it('uses strict JSON:API types for target decisions, school overrides and new event contracts', async () => {
  const transport=vi.fn().mockResolvedValue({status:200,headers:{'content-type':'application/vnd.api+json'},body:{data:null}})
  const api=createServiceOperationsClient(createClient(transport))
  await api.decision('target',1,'version',2,'approve','核验授权')
  await api.override('school','resource',0,'4:1',{subtitle:'',active:false})
  await api.batch('school','order','4:2',[{id:'resource',revision:1}])
  await api.resolve('school','resource')
  await api.draftPreview('school',{token:'4:2',at:'2026-11-21T00:00:00Z',resource_id:null,platform_default:false,draft:{revision:0,title:'示例草稿',subtitle:'',badge:'',image_ref:{kind:'asset',id:'image'},category_id:null,cooperation_id:null,action:{kind:'none'},active:true,featured:true,sort_order:0,starts_at:null,ends_at:null}})
  const documents=transport.mock.calls.map(([request])=>request.body ? JSON.parse(request.body).data : {type:resourceType(request.path)})
  expect(documents.map(value=>value.type)).toEqual(['operation-target-reviews','home-shortcut-overrides','shortcut-batches','operation-service-resolutions','home-shortcut-previews'])
  expect(documents[4].attributes.resource_id).toBeNull()
  expect(documents[1].attributes.presentation).toEqual({subtitle:'',active:false})
  expect(resourceType('/api/v1/schools/school/operation-action-events')).toBe('operation-action-events')
  expect(resourceType('/api/v1/schools/school/marketing-settings')).toBe('school-marketing')
  expect(transport.mock.calls[0][0].path).toBe('/api/v1/platform/operation-service-targets/target/approve')
  expect(documents[0].attributes).toEqual({revision:1,version_id:'version',version_revision:2,reason:'核验授权'})
  expect(transport.mock.calls[3][0].method).toBe('GET')
})
