it('binds wrapper resolution and report pagination to explicit identifiers',async()=>{
  const transport=vi.fn().mockResolvedValue({status:200,headers:{'content-type':'application/vnd.api+json'},body:{data:null}})
  const api=createServiceOperationsClient(createClient(transport))
  await api.resolve('school','resource','version','copy & link')
  await api.readReport(undefined,'snapshot',2,50)
  await api.report('school','2026-11-21T00:00:00+08:00','2026-11-22T00:00:00+08:00',{partner_id:'partner',placement:'home_shortcut'})
  expect(transport.mock.calls[0][0].path).toBe('/api/v1/schools/school/operation-services/resource/resolve?version=version&channel=copy%20%26%20link')
  expect(transport.mock.calls[1][0].path).toBe('/api/v1/platform/operation-reports/snapshot?page%5Bnumber%5D=2&page%5Bsize%5D=50')
  expect(JSON.parse(transport.mock.calls[2][0].body).data.attributes.partner_id).toBe('partner')
  expect(resourceType('/api/v1/platform/home-shortcuts/preview')).toBe('home-shortcut-previews')
})
